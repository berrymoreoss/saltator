/**
 * `node --import ./scripts/resolve-hooks.ts scripts/sample-65c02.ts` (R17a): writes the sample
 * of SingleStepTests `wdc65c02/v1` that `pnpm check` runs (`src/library/cpu/w65c02s-sst-sample.ts`)
 * from the cache `pnpm test:65c02` downloads. Per opcode: the first case of each cycle count
 * (page crossed or not, branch taken or not), the same in decimal mode for ADC and SBC, then
 * cases picked by a seed from the opcode up to `PER_OPCODE`. Deterministic: the same cache
 * gives the same file.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { hashString, SeededRandom } from '../src/core/index.ts';
import type { SingleStepCase, SingleStepState } from '../src/library/cpu/single-step.ts';
import { download, loadCases, SUITE_OPCODES } from './test-65c02.ts';

const PER_OPCODE = 8;
const OUT = fileURLToPath(new URL('../src/library/cpu/w65c02s-sst-sample.ts', import.meta.url));

const hex = (value: number, digits = 2) => value.toString(16).padStart(digits, '0');

function state(s: SingleStepState): string {
  return [hex(s.pc, 4), hex(s.s), hex(s.a), hex(s.x), hex(s.y), hex(s.p)].join(' ');
}

function ram(s: SingleStepState): string {
  return s.ram.map(([address, value]) => `${hex(address, 4)}:${hex(value)}`).join(' ');
}

/** One case on one line: `initial | ram | final | ram | cycles` (`1531ra9`, `0107w4c`). */
export function encodeCase(test: SingleStepCase): string {
  const cycles = test.cycles
    .map(
      ([address, value, kind]) => `${hex(address, 4)}${kind === 'write' ? 'w' : 'r'}${hex(value)}`,
    )
    .join(' ');
  return [state(test.initial), ram(test.initial), state(test.final), ram(test.final), cycles].join(
    ' | ',
  );
}

function pick(opcode: number, cases: readonly SingleStepCase[]): SingleStepCase[] {
  const chosen: SingleStepCase[] = [];
  const add = (test: SingleStepCase | undefined) => {
    if (test && !chosen.includes(test) && chosen.length < PER_OPCODE) chosen.push(test);
  };
  const decimalMatters =
    [0x61, 0x65, 0x69, 0x6d, 0x71, 0x72, 0x75, 0x79, 0x7d].includes(opcode) ||
    [0xe1, 0xe5, 0xe9, 0xed, 0xf1, 0xf2, 0xf5, 0xf9, 0xfd].includes(opcode);
  const counts = [...new Set(cases.map((test) => test.cycles.length))].sort((a, b) => a - b);
  for (const count of counts) {
    add(cases.find((test) => test.cycles.length === count && (test.initial.p & 0x08) === 0));
    if (decimalMatters) {
      add(cases.find((test) => test.cycles.length === count && (test.initial.p & 0x08) !== 0));
    }
  }
  const random = new SeededRandom(hashString(`wdc65c02 ${hex(opcode)}`));
  while (chosen.length < Math.min(PER_OPCODE, cases.length)) {
    add(cases[random.nextUint32() % cases.length]);
  }
  return chosen;
}

