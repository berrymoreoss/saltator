/**
 * `pnpm hdl:library` (HDL-2): compiles the library's parts written in Verilog —
 * `src/library/verilog/*.v` — with the system `yosys` and the command modules are made with,
 * converts each to the IR and writes them, with each source's SHA-256, to
 * `src/library/verilog/modules.ts` (formatted by Biome), so the app and `pnpm check` never run
 * Yosys. A source that converts with any message (an error or a warning) stops the script: a
 * library part is clean. `scripts/hdl-library.test.ts` fails when a source changed since.
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromYosys } from '../src/library/hdl/from-yosys.ts';
import { librarySourceHash } from './hdl-library-hash.ts';
import { hasYosys, runYosys } from './yosys.ts';

const DIR = fileURLToPath(new URL('../src/library/verilog/', import.meta.url));
const OUT = join(DIR, 'modules.ts');

/** A string literal in single quotes, as Biome writes them. */
const quote = (text: string) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

if (!hasYosys()) {
  console.error('yosys is not on the PATH (macOS: brew install yosys)');
  process.exit(2);
}

const entries: string[] = [];
let creator = '';
for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith('.v'))
  .sort()) {
  const path = join(DIR, file);
  const run = runYosys(path);
  if (run.json === undefined) {
    console.error(`${file}: yosys failed\n${run.log}`);
    process.exit(1);
  }
  const { module, messages } = fromYosys(run.json);
  if (!module || messages.length > 0) {
    console.error(
      `${file}:\n  ${messages.map((m) => `${m.src ?? '-'}: ${m.message}`).join('\n  ')}`,
    );
    process.exit(1);
  }
  creator = module.creator;
  const name = file.replace(/\.v$/, '');
  const hash = librarySourceHash(readFileSync(path, 'utf8'));
  entries.push(
    `  ${quote(name)}: { sha256: ${quote(hash)}, ir: ${quote(JSON.stringify(module))} },`,
  );
  console.log(`${file} → ${module.top}`);
}

writeFileSync(
  OUT,
  `/**
 * Generated by scripts/hdl-library.ts (\`pnpm hdl:library\`) — do not edit. The IR of the
 * library's parts written in Verilog (HDL-2), compiled from the sources in this folder by
 * ${creator}, each with its source's SHA-256: \`scripts/hdl-library.test.ts\` fails when a source
 * changed without a new run.
 */
export const LIBRARY_MODULES: Readonly<
  Record<string, { readonly sha256: string; readonly ir: string }>
> = {
${entries.join('\n')}
};
`,
);
spawnSync('pnpm', ['biome', 'format', '--write', OUT], { stdio: 'ignore' });
console.log(`wrote ${entries.length} modules`);
