/**
 * `pnpm hdl:fixtures` (HDL-1): synthesizes every `src/library/hdl/fixtures/*.v` with the system
 * `yosys` (`scripts/yosys.ts`) and writes their JSON netlists, compacted, to
 * `src/library/hdl/fixtures.ts` (formatted by Biome), which the converter's tests read — so
 * `pnpm check` never runs Yosys. A source Yosys fails on stops the script.
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hasYosys, runYosys } from './yosys.ts';

const DIR = fileURLToPath(new URL('../src/library/hdl/fixtures/', import.meta.url));
const OUT = fileURLToPath(new URL('../src/library/hdl/fixtures.ts', import.meta.url));

/** A string literal in single quotes, as Biome writes them. */
const quote = (text: string) => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

if (!hasYosys()) {
  console.error('yosys is not on the PATH (macOS: brew install yosys)');
  process.exit(2);
}

const entries: string[] = [];
let creator = '';
for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith('.v'))
  .sort()) {
  const run = runYosys(join(DIR, file));
  if (run.json === undefined) {
    console.error(`${file}: yosys failed\n${run.log}`);
    process.exit(1);
  }
  const parsed = JSON.parse(run.json) as { creator?: string };
  creator = parsed.creator ?? creator;
  entries.push(`  ${quote(file.replace(/\.v$/, ''))}: ${quote(JSON.stringify(parsed))},`);
  console.log(`${file}${run.log === '' ? '' : `\n  ${run.log.replaceAll('\n', '\n  ')}`}`);
}

writeFileSync(
  OUT,
  `/**
 * Generated by scripts/hdl-fixtures.ts (\`pnpm hdl:fixtures\`) — do not edit. Yosys's JSON
 * netlists of the sources in ./fixtures/, compacted, for the converter's tests; made by
 * ${creator}.
 */
export const YOSYS_FIXTURES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`,
);
spawnSync('pnpm', ['biome', 'format', '--write', OUT], { stdio: 'ignore' });
console.log(`wrote ${entries.length} fixtures`);
